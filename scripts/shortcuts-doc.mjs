/*
 * The keyboard pages of the docs (docs/en/keyboard.md, docs/de/keyboard.md), made from the shortcut catalog
 * (resources/js/lib/shortcuts/catalog.ts), the keys of the widgets (widgets.ts) and their texts in lang/*.json.
 * `ddev exec pnpm shortcuts:doc` writes both pages; scripts/shortcuts-doc.test.mjs checks that they are what this script
 * writes, so a changed shortcut changes the pages in the same commit. Node loads the two .ts files by type stripping:
 * they import types only. Keys bound twice are caught by catalog.test.ts, which can read the registry (K14).
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SHORTCUTS } from '../resources/js/lib/shortcuts/catalog.ts';
import { WIDGET_KEYS } from '../resources/js/lib/shortcuts/widgets.ts';

const ROOT = path.resolve(import.meta.dirname, '..');

export const DOC_PATHS = { en: 'docs/en/keyboard.md', de: 'docs/de/keyboard.md' };

const COMMENT =
  '<!-- Generated by scripts/shortcuts-doc.mjs from resources/js/lib/shortcuts/catalog.ts and widgets.ts. Do not edit; run `ddev exec pnpm shortcuts:doc`. -->';

/** Keys whose name differs by language. */
const WORDS = {
  en: { mod: '⌘ / Ctrl', space: 'Space', home: 'Home', end: 'End' },
  de: { mod: '⌘ / Strg', space: 'Leertaste', home: 'Pos1', end: 'Ende' },
};

/** Between the steps of a sequence ("G then I"). */
const THEN = { en: ' then ', de: ', dann ' };

/** Keys with the same name in both languages, in register spelling (and its aliases). */
const NAMES = {
  shift: '⇧',
  alt: '⌥ / Alt',
  enter: '↵',
  return: '↵',
  escape: 'Esc',
  esc: 'Esc',
  backspace: '⌫',
  up: '↑',
  arrowup: '↑',
  down: '↓',
  arrowdown: '↓',
  left: '←',
  arrowleft: '←',
  right: '→',
  arrowright: '→',
};

const TEXT = {
  en: {
    title: 'Keyboard',
    keys: 'Keys',
    action: 'Action',
    intro: [
      'werkbuch works without a mouse. Press <kbd>?</kbd> on any screen to see the shortcuts that apply there right now; this page lists all of them.',
      'Where a key has two names, the first is the key on a Mac and the second the one on Windows and Linux.',
      `While you type in a field, only ${keyLabel('mod+k', 'en')}, ${keyLabel('escape', 'en')} and ${keyLabel('mod+enter', 'en')} work. While a dialog is open, the shortcuts of the page behind it wait.`,
    ].join(' '),
  },
  de: {
    title: 'Tastatur',
    keys: 'Taste',
    action: 'Aktion',
    intro: [
      'werkbuch geht ohne Maus. Mit <kbd>?</kbd> zeigt jeder Bildschirm die Kürzel, die dort gerade gelten; diese Seite nennt alle.',
      'Hat eine Taste zwei Namen, gilt der erste auf dem Mac und der zweite unter Windows und Linux.',
      `Beim Tippen in einem Feld wirken nur ${keyLabel('mod+k', 'de')}, ${keyLabel('escape', 'de')} und ${keyLabel('mod+enter', 'de')}. Solange ein Dialog offen ist, ruhen die Kürzel der Seite dahinter.`,
    ].join(' '),
  },
};

/** One key as written on the page. */
function keyName(token, language) {
  const name = token.toLowerCase();
  if (Object.hasOwn(WORDS[language], name)) return WORDS[language][name];
  if (Object.hasOwn(NAMES, name)) return NAMES[name];
  return token.length === 1 ? token.toUpperCase() : token;
}

/** Register notation ("mod+shift+k", "g i") as keys in `<kbd>`: `+` joins keys pressed together, a word the steps. */
export function keyLabel(keys, language) {
  return keys
    .trim()
    .split(/\s+/)
    .map((step) =>
      (step === '+' ? ['+'] : step.split('+').filter(Boolean))
        .map((token) => `<kbd>${cell(keyName(token, language))}</kbd>`)
        .join('+'),
    )
    .join(THEN[language]);
}

/** Text from lang/*.json inside a table cell. */
function cell(text) {
  return text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('|', '\\|');
}

/** Rows of a table: the keys of entries with the same label in one row, in the order they first appear. */
function rows(entries, language, texts) {
  const byLabel = new Map();
  for (const entry of entries) {
    const keys = byLabel.get(entry.label) ?? [];
    if (!keys.includes(entry.keys)) keys.push(entry.keys);
    byLabel.set(entry.label, keys);
  }
  return [...byLabel].map(([label, keys]) => `| ${keys.map((key) => keyLabel(key, language)).join(' / ')} | ${cell(texts[label])} |`);
}

function section(title, entries, language, texts) {
  const { keys, action } = TEXT[language];
  return [`## ${cell(title)}`, '', `| ${keys} | ${action} |`, '| --- | --- |', ...rows(entries, language, texts), ''];
}

/** The keyboard page of a language: the groups of the catalog in catalog order, then the widgets. */
export async function renderKeyboardDoc(language) {
  const texts = JSON.parse(await fs.promises.readFile(path.join(ROOT, 'lang', `${language}.json`), 'utf8'));
  const groups = new Map();
  for (const entry of Object.values(SHORTCUTS)) groups.set(entry.group, [...(groups.get(entry.group) ?? []), entry]);

  return [
    COMMENT,
    '',
    `# ${TEXT[language].title}`,
    '',
    TEXT[language].intro,
    '',
    ...[...groups].flatMap(([group, entries]) => section(texts[group], entries, language, texts)),
    ...WIDGET_KEYS.flatMap((widget) => section(texts[widget.group], widget.entries, language, texts)),
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [language, file] of Object.entries(DOC_PATHS)) {
    fs.writeFileSync(path.join(ROOT, file), await renderKeyboardDoc(language));
  }
}
